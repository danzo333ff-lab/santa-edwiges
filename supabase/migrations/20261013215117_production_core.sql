create or replace function public.update_commercial_setting(p_key text, p_value text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select public.is_admin()) then
    raise exception 'Acesso de administrador necessário.' using errcode = '42501';
  end if;
  if p_key is null
     or p_key not in ('minimum_order', 'delivery_fee', 'cash_discount_percent', 'card_fee_percent') then
    raise exception 'Configuração comercial inválida.' using errcode = '22023';
  end if;
  if p_value is null or p_value !~ '^[0-9]+([.][0-9]{1,2})?$' then
    raise exception 'Valor comercial inválido.' using errcode = '22023';
  end if;
  if p_value::numeric < 0 then
    raise exception 'Valor comercial inválido.' using errcode = '22023';
  end if;
  if p_key in ('cash_discount_percent', 'card_fee_percent')
     and p_value::numeric > 100 then
    raise exception 'A taxa ou desconto não pode passar de 100%%.' using errcode = '22023';
  end if;

  insert into public.settings (key, value, updated_at)
  values (p_key, p_value, now())
  on conflict (key) do update set value = excluded.value, updated_at = now();
end;
$$;

create or replace function public.refresh_overdue_payments()
returns integer
language plpgsql
