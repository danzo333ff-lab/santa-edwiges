create or replace function public.create_order(
  p_items jsonb,
  p_payment_method text,
  p_idempotency_key uuid,
  p_delivery_address text default null,
  p_note text default null,
  p_payment_term_days integer default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer uuid := (select auth.uid());
  profile_row public.profiles%rowtype;
  item jsonb;
  product_row public.products%rowtype;
  normalized_items jsonb;
  item_count integer;
  product_id bigint;
  quantity integer;
  unit_price numeric(12, 2);
  line_subtotal numeric(12, 2);
  subtotal_amount numeric(12, 2) := 0;
  delivery_amount numeric(12, 2) := 0;
  discount_rate numeric(8, 5) := 0;
  fee_rate numeric(8, 5) := 0;
  discount_value numeric(12, 2) := 0;
  fee_value numeric(12, 2) := 0;
  total_amount numeric(12, 2);
  minimum_amount numeric(12, 2) := 0;
  new_order_id bigint;
  order_number_value text;
  existing_order_id bigint;
  term_due date;
  delivery_address_value text;
begin
  if customer is null then
    raise exception 'É necessário entrar na conta para finalizar o pedido.'
      using errcode = '42501';
  end if;
  if p_idempotency_key is null then
    raise exception 'Chave de idempotência obrigatória.' using errcode = '22023';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'O carrinho deve ser uma lista de itens válida.'
      using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 100 then
    raise exception 'O carrinho precisa conter de 1 a 100 itens.'
      using errcode = '22023';
  end if;
  if p_payment_method is null
     or p_payment_method not in ('pix', 'dinheiro', 'cartao', 'combinar', 'prazo') then
    raise exception 'Forma de pagamento inválida.' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(customer::text || ':' || p_idempotency_key::text, 0)
  );

  select o.id into existing_order_id
  from public.orders o
  where o.customer_id = customer
    and o.idempotency_key = p_idempotency_key;
  if existing_order_id is not null then
    return existing_order_id;
  end if;

  select * into profile_row
  from public.profiles p
  where p.id = customer
  for update;
  if not found or profile_row.role <> 'cliente' or profile_row.status <> 'ativo' then
    raise exception 'A conta precisa estar aprovada para fazer pedidos.'
      using errcode = '42501';
  end if;

  if p_payment_method = 'prazo' then
    if p_payment_term_days not in (3, 7, 14) then
      raise exception 'Prazo de pagamento inválido.' using errcode = '22023';
    end if;
    if not exists (
      select 1 from public.customer_payment_terms t
      where t.customer_id = customer
        and t.days = p_payment_term_days
        and t.enabled
    ) then
      raise exception 'Este prazo não foi autorizado para sua conta.'
        using errcode = '42501';
    end if;
  elsif p_payment_term_days is not null then
    raise exception 'Prazo só pode ser informado para pagamento a prazo.'
      using errcode = '22023';
  end if;

  delivery_address_value := coalesce(
    nullif(trim(p_delivery_address), ''),
    nullif(concat_ws(', ',
      nullif(trim(profile_row.endereco), ''),
      nullif(trim(profile_row.numero), ''),
      nullif(trim(profile_row.bairro), ''),
      nullif(trim(profile_row.cidade), ''),
      nullif(trim(profile_row.cep), '')
    ), '')
  );
  if delivery_address_value is null then
    raise exception 'Informe um endereço de entrega no perfil ou no pedido.'
      using errcode = '22023';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_items) as entry
    where coalesce(entry ->> 'product_id', '') !~ '^[1-9][0-9]*$'
       or coalesce(entry ->> 'quantity', '') !~ '^[1-9][0-9]*$'
  ) then
    raise exception 'Produto ou quantidade inválida.' using errcode = '22023';
  end if;

  select jsonb_agg(jsonb_build_object('product_id', grouped.product_id, 'quantity', grouped.quantity))
    into normalized_items
  from (
    select (entry ->> 'product_id')::bigint as product_id,
           sum((entry ->> 'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) as entry
    group by (entry ->> 'product_id')::bigint
  ) grouped;

  select count(*) into item_count from jsonb_array_elements(normalized_items);
  if item_count = 0 then
    raise exception 'O carrinho está vazio.' using errcode = '22023';
  end if;

  perform p.id
  from public.products p
  where p.id in (
    select (entry ->> 'product_id')::bigint
    from jsonb_array_elements(normalized_items) as entry
  )
  order by p.id
  for update;

  for item in select value from jsonb_array_elements(normalized_items)
  loop
    product_id := (item ->> 'product_id')::bigint;
    quantity := (item ->> 'quantity')::integer;

    select * into product_row
    from public.products p
    where p.id = product_id;
    if not found or not product_row.active then
      raise exception 'Um produto do carrinho não está mais disponível.'
        using errcode = '22023';
    end if;
    if product_row.stock_fisico - product_row.stock_reservado < quantity then
      raise exception 'Estoque insuficiente para o produto %.', product_row.name
        using errcode = '22023';
    end if;

    unit_price := case
      when product_row.bulk_min is not null
        and quantity >= product_row.bulk_min
        then product_row.bulk_price
      else product_row.price
    end;
    line_subtotal := round(unit_price * quantity, 2);
    subtotal_amount := subtotal_amount + line_subtotal;
  end loop;

  select coalesce(max(s.value::numeric), 0) into delivery_amount
  from public.settings s where s.key = 'delivery_fee';
  select coalesce(max(s.value::numeric), 0) into minimum_amount
  from public.settings s where s.key = 'minimum_order';

  if subtotal_amount < minimum_amount then
    raise exception 'O pedido mínimo é R$ %.', to_char(minimum_amount, 'FM999G999G990D00')
      using errcode = '22023';
  end if;

  if p_payment_method = 'dinheiro' then
    select coalesce(max(s.value::numeric), 1) / 100 into discount_rate
    from public.settings s where s.key = 'cash_discount_percent';
    discount_value := round(subtotal_amount * discount_rate, 2);
  elsif p_payment_method = 'cartao' then
    select coalesce(max(s.value::numeric), 3) / 100 into fee_rate
    from public.settings s where s.key = 'card_fee_percent';
    fee_value := round(subtotal_amount * fee_rate, 2);
  end if;

  if p_payment_method = 'prazo' then
    term_due := (timezone('America/Sao_Paulo', now()))::date + p_payment_term_days;
  end if;
  total_amount := subtotal_amount + delivery_amount + fee_value - discount_value;
  order_number_value := 'SE-' || lpad(nextval('public.order_number_seq')::text, 6, '0');

  insert into public.orders (
    customer_id,
    order_number,
    status,
    subtotal,
    delivery_fee,
    discount_amount,
    fee_amount,
    total,
    payment_method,
    payment_status,
    payment_term_days,
    due_date,
    delivery_address,
    customer_company,
    customer_phone,
    observation,
    cart_token,
    idempotency_key
  )
  values (
    customer,
    order_number_value,
    'pendente',
    subtotal_amount,
    delivery_amount,
    discount_value,
    fee_value,
    total_amount,
    p_payment_method,
    case when p_payment_method = 'prazo' then 'em_aberto'::public.payment_status else null end,
    p_payment_term_days,
    term_due,
    delivery_address_value,
    profile_row.empresa,
    coalesce(profile_row.whatsapp, profile_row.telefone),
    nullif(trim(p_note), ''),
    p_idempotency_key::text,
    p_idempotency_key
  )
  returning id into new_order_id;

  insert into public.order_status_history (order_id, from_status, to_status, changed_by, note)
  values (new_order_id, null, 'pendente', customer, 'Pedido recebido');

  for item in select value from jsonb_array_elements(normalized_items)
  loop
    product_id := (item ->> 'product_id')::bigint;
    quantity := (item ->> 'quantity')::integer;

    select * into product_row from public.products p where p.id = product_id;
    unit_price := case
      when product_row.bulk_min is not null
        and quantity >= product_row.bulk_min
        then product_row.bulk_price
      else product_row.price
    end;
    line_subtotal := round(unit_price * quantity, 2);

    insert into public.order_items (
      order_id,
      product_id,
      product_name,
      unit,
      quantity,
      price_at_purchase,
      subtotal
    )
    values (
      new_order_id,
      product_id,
      product_row.name,
      product_row.unit,
      quantity,
      unit_price,
      line_subtotal
    );

    update public.products
    set stock_reservado = stock_reservado + quantity
    where id = product_id;

    insert into public.stock_movements (
      product_id,
      order_id,
      movement_type,
      quantity,
      reason,
      responsible_id
    )
    values (
      product_id,
      new_order_id,
      'reserva',
      quantity,
      'Reserva do pedido ' || order_number_value,
      customer
    );
  end loop;

  return new_order_id;
end;
$$;

create or replace function public.update_order_status(
  p_order_id bigint,
  p_new_status public.pedido_status,
  p_note text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  order_row public.orders%rowtype;
  valid_transition boolean;
  item record;
begin
  if not (select public.is_staff_or_admin()) then
    raise exception 'Acesso administrativo necessário.' using errcode = '42501';
  end if;

  select * into order_row from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Pedido não encontrado.' using errcode = 'P0002';
  end if;

  valid_transition :=
    (order_row.status = 'pendente' and p_new_status in ('aprovado', 'em_preparo', 'cancelado', 'rejeitado'))
    or (order_row.status = 'aprovado' and p_new_status in ('em_preparo', 'cancelado', 'rejeitado'))
    or (order_row.status = 'em_preparo' and p_new_status in ('enviado', 'cancelado'))
    or (order_row.status = 'enviado' and p_new_status = 'concluido');
  if not valid_transition then
    raise exception 'Transição de status inválida.' using errcode = '22023';
  end if;

  if p_new_status = 'concluido' then
    for item in select oi.product_id, oi.quantity, oi.product_name
      from public.order_items oi where oi.order_id = p_order_id
      order by oi.product_id
    loop
      update public.products
      set stock_fisico = stock_fisico - item.quantity,
          stock_reservado = stock_reservado - item.quantity
      where id = item.product_id
        and stock_fisico >= item.quantity
        and stock_reservado >= item.quantity;
      if not found then
        raise exception 'Estoque inconsistente para o produto %.', item.product_name
          using errcode = '23514';
      end if;
      insert into public.stock_movements (
        product_id, order_id, movement_type, quantity, reason, responsible_id
      )
      values (
        item.product_id, p_order_id, 'saida', -item.quantity,
        'Entrega do pedido ' || order_row.order_number, (select auth.uid())
      );
    end loop;
  elsif p_new_status in ('cancelado', 'rejeitado') then
    for item in select oi.product_id, oi.quantity, oi.product_name
      from public.order_items oi where oi.order_id = p_order_id
      order by oi.product_id
    loop
      update public.products
      set stock_reservado = stock_reservado - item.quantity
      where id = item.product_id and stock_reservado >= item.quantity;
      if not found then
        raise exception 'Reserva inconsistente para o produto %.', item.product_name
          using errcode = '23514';
      end if;
      insert into public.stock_movements (
        product_id, order_id, movement_type, quantity, reason, responsible_id
      )
      values (
        item.product_id, p_order_id, 'liberacao', -item.quantity,
        'Liberação do pedido ' || order_row.order_number, (select auth.uid())
      );
    end loop;
    if order_row.payment_status in ('em_aberto', 'vencido') then
      update public.orders set payment_status = 'cancelado' where id = p_order_id;
    end if;
  end if;

  update public.orders set status = p_new_status where id = p_order_id;
  insert into public.order_status_history (
    order_id, from_status, to_status, changed_by, note
  )
  values (
    p_order_id, order_row.status, p_new_status, (select auth.uid()), nullif(trim(p_note), '')
  );
end;
$$;

create or replace function public.cancel_my_order(p_order_id bigint, p_note text default null)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  order_row public.orders%rowtype;
  item record;
begin
  select * into order_row
  from public.orders
  where id = p_order_id and customer_id = (select auth.uid())
  for update;
  if not found then
    raise exception 'Pedido não encontrado.' using errcode = 'P0002';
  end if;
  if order_row.status <> 'pendente' then
    raise exception 'Este pedido não pode mais ser cancelado pelo cliente.'
      using errcode = '22023';
  end if;

  for item in select oi.product_id, oi.quantity, oi.product_name
    from public.order_items oi where oi.order_id = p_order_id
    order by oi.product_id
  loop
    update public.products
    set stock_reservado = stock_reservado - item.quantity
    where id = item.product_id and stock_reservado >= item.quantity;
    if not found then
      raise exception 'Reserva inconsistente para o produto %.', item.product_name
        using errcode = '23514';
    end if;
    insert into public.stock_movements (
      product_id, order_id, movement_type, quantity, reason, responsible_id
    )
    values (
      item.product_id, p_order_id, 'liberacao', -item.quantity,
      'Cancelamento do pedido pelo cliente', (select auth.uid())
    );
  end loop;

  update public.orders
  set status = 'cancelado',
      payment_status = case
        when payment_status in ('em_aberto', 'vencido') then 'cancelado'
        else payment_status
      end
  where id = p_order_id;
  insert into public.order_status_history (
    order_id, from_status, to_status, changed_by, note
  )
  values (
    p_order_id, order_row.status, 'cancelado', (select auth.uid()), nullif(trim(p_note), '')
  );
end;
$$;

