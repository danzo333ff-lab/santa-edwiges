create or replace function public.mark_payment(
  p_order_id bigint,
  p_amount numeric default null,
  p_method text default 'manual',
  p_note text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  order_row public.orders%rowtype;
  amount_to_record numeric(12, 2);
begin
  if not (select public.is_staff_or_admin()) then
    raise exception 'Acesso administrativo necessário.' using errcode = '42501';
  end if;

  select * into order_row from public.orders where id = p_order_id for update;
  if not found or order_row.payment_status is null then
    raise exception 'Conta a prazo não encontrada.' using errcode = 'P0002';
  end if;
  if order_row.payment_status = 'cancelado' then
    raise exception 'Pedido cancelado não pode receber pagamento.' using errcode = '22023';
  end if;
  amount_to_record := coalesce(p_amount, order_row.total);
  if amount_to_record <= 0 or amount_to_record + coalesce((
    select sum(pr.amount)
    from public.payment_records pr
    where pr.order_id = p_order_id
  ), 0) > order_row.total then
    raise exception 'Valor de pagamento inválido.' using errcode = '22023';
  end if;

  insert into public.payment_records (order_id, amount, method, recorded_by, note)
  values (p_order_id, amount_to_record, p_method, (select auth.uid()), nullif(trim(p_note), ''));

  if amount_to_record + coalesce((
    select sum(pr.amount)
    from public.payment_records pr
    where pr.order_id = p_order_id
  ), 0) = order_row.total then
    update public.orders set payment_status = 'pago' where id = p_order_id;
  end if;
end;
$$;

create or replace function public.register_stock_movement(
  p_product_id bigint,
  p_type public.movimento_tipo,
  p_quantity integer,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  product_row public.products%rowtype;
  next_stock integer;
begin
  if not (select public.is_admin()) then
    raise exception 'Acesso de administrador necessário.' using errcode = '42501';
  end if;
  if p_type not in ('entrada', 'saida', 'ajuste') or p_quantity <= 0 or nullif(trim(p_reason), '') is null then
    raise exception 'Movimentação de estoque inválida.' using errcode = '22023';
  end if;

  select * into product_row from public.products where id = p_product_id for update;
  if not found then
    raise exception 'Produto não encontrado.' using errcode = 'P0002';
  end if;
  next_stock := case
    when p_type = 'entrada' then product_row.stock_fisico + p_quantity
    when p_type = 'saida' then product_row.stock_fisico - p_quantity
    else p_quantity
  end;
  if next_stock < product_row.stock_reservado or next_stock < 0 then
    raise exception 'A quantidade deixaria o estoque abaixo das reservas existentes.'
      using errcode = '23514';
  end if;

  update public.products set stock_fisico = next_stock where id = p_product_id;
  insert into public.stock_movements (
    product_id, movement_type, quantity, reason, responsible_id
  )
  values (
    p_product_id,
    p_type,
    case when p_type = 'saida' then -p_quantity else p_quantity end,
    trim(p_reason),
    (select auth.uid())
  );
end;
$$;

