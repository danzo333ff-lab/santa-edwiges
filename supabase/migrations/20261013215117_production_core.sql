create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_row jsonb;
  new_row jsonb;
  record_key text;
begin
  if tg_op <> 'INSERT' then
    old_row := to_jsonb(old);
  end if;
  if tg_op <> 'DELETE' then
    new_row := to_jsonb(new);
  end if;

  record_key := coalesce(new_row ->> 'id', old_row ->> 'id');
  if record_key is null then
    record_key := coalesce(new_row ->> 'customer_id', old_row ->> 'customer_id');
  end if;

  insert into public.audit_logs (
    actor_id,
    action,
    table_name,
    record_id,
    old_values,
    new_values
  )
  values (
    (select auth.uid()),
    lower(tg_op),
    tg_table_name,
    coalesce(record_key, 'unknown'),
    old_row,
    new_row
  );
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

